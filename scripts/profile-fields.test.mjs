import assert from "node:assert/strict";
import { test } from "node:test";

import {
  ADMIN_EDITABLE_FIELDS,
  CADET_EDITABLE_FIELDS,
  FIELD_OWNERSHIP,
  ROSTER_CONTROLLED_FIELDS,
  SYSTEM_CONTROLLED_FIELDS,
  buildNewProfileData,
  buildRosterProfileUpdate,
  computeProfileCompletion,
  selectAllowedFields,
} from "../src/lib/profile-fields.mjs";

test("every profile field has exactly one owner", () => {
  const owners = new Set(Object.values(FIELD_OWNERSHIP));

  assert.deepEqual([...owners].sort(), ["ADMIN", "CADET", "ROSTER", "SYSTEM"]);
  assert.equal(
    CADET_EDITABLE_FIELDS.includes("wing"),
    false,
    "a cadet must not own a roster field"
  );
  assert.equal(
    ADMIN_EDITABLE_FIELDS.includes("status"),
    false,
    "the approval mirror is never writable"
  );
  assert.equal(
    SYSTEM_CONTROLLED_FIELDS.includes("photoUrl"),
    true,
    "the photo object name is generated by the server"
  );
  assert.equal(
    ROSTER_CONTROLLED_FIELDS.includes("prn"),
    true,
    "the PRN is maintained through the roster"
  );
});

test("an unknown field is rejected instead of being ignored", () => {
  const result = selectAllowedFields(
    { phone: "9876543210", status: "APPROVED" },
    CADET_EDITABLE_FIELDS
  );

  assert.equal(result.ok, false);
  assert.equal(result.errors.length, 1);
  assert.equal(result.errors[0].field, "status");
});

test("a roster controlled field is rejected for a cadet with a clear message", () => {
  const result = selectAllowedFields({ wing: "Navy" }, CADET_EDITABLE_FIELDS);

  assert.equal(result.ok, false);
  assert.match(result.errors[0].message, /roster/i);
});

test("an allowed field is accepted", () => {
  const result = selectAllowedFields(
    { phone: "9876543210", address: "Campus" },
    CADET_EDITABLE_FIELDS
  );

  assert.equal(result.ok, true);
  assert.deepEqual(result.values, {
    phone: "9876543210",
    address: "Campus",
  });
});

test("the completion meter reports the missing fields", () => {
  const completion = computeProfileCompletion({
    fullName: "Cadet",
    wing: "Army",
    year: "2nd Year",
    branch: "Computer Science",
    division: "SD",
    dob: new Date("2005-01-01"),
    bloodGroup: "O+",
    gender: "Male",
    phone: "9876543210",
    photoUrl: null,
  });

  assert.equal(completion.missing.length, 1);
  assert.equal(completion.missing[0].field, "photoUrl");
  assert.equal(completion.percent, 90);
  assert.equal(completion.total, 10);
});

test("a missing profile is completely empty", () => {
  const completion = computeProfileCompletion(null);

  assert.equal(completion.percent, 0);
  assert.equal(completion.completed, 0);
  assert.equal(completion.missing.length, 10);
});

test("the roster writes its own fields and never erases a stored value", () => {
  const profile = {
    fullName: "Old Name",
    prn: "PRN001",
    wing: "Army",
    year: "2nd Year",
    branch: "Computer Science",
  };

  const { data, changed } = buildRosterProfileUpdate(profile, {
    fullName: "New Name",
    prn: "PRN002",
    wing: null,
    year: "3rd Year",
    branch: "Computer Science",
  });

  assert.deepEqual(data, {
    fullName: "New Name",
    prn: "PRN002",
    year: "3rd Year",
  });
  assert.deepEqual(changed.sort(), ["fullName", "prn", "year"]);
});

test("the roster never writes a cadet controlled field", () => {
  const { data } = buildRosterProfileUpdate(
    { phone: "9876543210", bloodGroup: "O+" },
    {
      fullName: "Cadet",
      phone: "0000000000",
      bloodGroup: "A+",
      address: "Somewhere",
    }
  );

  assert.equal(data.phone, undefined);
  assert.equal(data.bloodGroup, undefined);
  assert.equal(data.address, undefined);
});

test("a new profile is built from the roster and leaves the cadet fields empty", () => {
  const data = buildNewProfileData(
    { name: "Google Name" },
    {
      fullName: "Roster Name",
      prn: "PRN003",
      wing: "Navy",
      division: "SD",
      year: "1st Year",
      branch: "Mechanical",
    }
  );

  assert.equal(data.fullName, "Roster Name");
  assert.equal(data.wing, "Navy");
  assert.equal(data.prn, "PRN003");
  assert.equal(data.phone, undefined);
  assert.equal(data.dob, undefined);
});
